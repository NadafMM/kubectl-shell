import type { Cluster, KObject } from "./model";

function pod(
  ns: string,
  name: string,
  status: string,
  age: string,
  containers: string[],
  labels: Record<string, string>,
): KObject {
  return {
    kind: "pod",
    ns,
    name,
    status,
    age,
    labels,
    containers: containers.map((container) => ({ name: container })),
  };
}

